"""Emit deterministic ODCS v3.1 data contracts for served tables.

Ergasterion reads the compiled dbt manifest, domain configuration, and source declarations.
It writes one contract per served canonical or mart model, excluding intermediate helpers.
Each contract records schema, keys, quality checks, survivorship provenance, and any
declared authoritative-model link.

Inputs (all read-only; the declarations stay SSOT):
  - target/manifest.json          the dbt manifest (offline `dbt parse`) -- served-model
                                  schema (documented columns), materialization, and the
                                  generic + singular dbt TESTS attached to each model.
  - domains/*.yml `odcs:` block   per-domain boundary config: ODCS domain name, contract
                                  version/status, target-warehouse server, optional
                                  authoritativeDefinitions link, and the served-product
                                  list (each optionally bound to a survivorship entity).
  - declarations/*.yml            source priority order feeding each survivorship entity.

Outputs:
  - contracts/<domain>/<table>.odcs.yml   one ODCS v3.1.0 contract per served table,
                                          regenerated-never-hand-edited.

Contract ids are
`dpf:<domain>:<table>` and versions come from the domain config -- no timestamps, no
UUIDs, no manifest-metadata leakage. The same manifest regenerates byte-identical output.
Every emitted contract is validated in-process against the vendored ODCS v3.1 JSON Schema
(schemas/odcs-json-schema-v3.1.0.json) without network access.

Usage:
    python ergasterion/emit_contracts.py            # write + validate every contract
    python ergasterion/emit_contracts.py --check    # validate + fail if on-disk drifted / hand-edited
"""

