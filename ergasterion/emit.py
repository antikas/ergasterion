# A bridge expression that maps a constant null into the effective column. Such a
# satellite never advances a consumption watermark, so a declared table whose source
# carries one gets a warning naming it.
NULL_CONSTANT_RE = re.compile(
    r"^(?:null|cast\s*\(\s*null\s+as\s+[^()]*\))$", re.IGNORECASE
)

# The marker lines macros/estate_evolution.sql logs its watermark facts on. A normal run
