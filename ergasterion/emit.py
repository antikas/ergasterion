def _normalise_logical_type(value: Any) -> str | None:
    """One normalised logical output type string per payload column.

    A type fact reaches the ledger as a bare token (``utf8_string``), a parameterised
    object (``decimal`` with precision and scale, ``local_datetime`` with a timezone),
    or the equivalent Pydantic model on a Bronze Product Contract. All three normalise
    to the same lowercase string, so the recorded fact compares on meaning.
    """
    if value is None:
        return None
    if hasattr(value, "value") and not isinstance(value, (str, bytes, dict)):
        # A str-valued enum member (SimpleLogicalType).
        value = value.value
    if isinstance(value, str):
        text = value.strip().lower()
        return text or None
    if hasattr(value, "model_dump"):
        value = value.model_dump(mode="json")
    if isinstance(value, dict):
        kind = value.get("kind") or value.get("logical_type")
        if kind is None:
            return None
        parameters = [
            f"{key}={value[key]}"
            for key in sorted(value)
            if key not in ("kind", "logical_type")
        ]
        rendered = str(kind).strip().lower()
        if parameters:
            rendered += "(" + ",".join(parameters) + ")"
        return rendered
    return None


def _bare_source_column(expression: Any) -> str | None:
    """The staging column a bridge select maps straight through, or None.

    A pass-through (``source.fund_name``) carries the staging column's own declared
    type to the payload column. Any other expression is a factory-owned transform whose
    output type the declarations do not state, so it contributes no type fact.
    """
    if not isinstance(expression, str):
        return None
    match = re.fullmatch(r"source\.([A-Za-z_][A-Za-z0-9_]*)", expression.strip())
    return match.group(1) if match else None


def payload_type_facts(
    declarations: list[dict[str, Any]],
    entity_configs: dict[str, dict[str, Any]],
    typed: Any | None = None,
) -> dict[str, dict[str, str]]:
    """Per entity, the normalised logical output type of every payload column that
    carries a type fact.

    Two facts feed it, in precedence order: the declared type on the staging
    projection column (``logical_type``), and the Bronze Product Contract's
    source-native schema for the physical column that projection column reads. A
    payload column whose sibling sources state different types carries no single fact,
    so the ledger records none and grading stays silent on it.
    """
    observed: dict[str, dict[str, set[str]]] = {}
    for declaration in declarations:
        source_name = declaration["source"]["name"]
        for table_name, table in declaration.get("tables", {}).items():
            projection = {
                column["name"]: column for column in table.get("projection", []) or []
            }
            native_types: dict[str, Any] = {}
            typed_tables = getattr(typed, "tables", None) if typed is not None else None
            if isinstance(typed_tables, dict):
                typed_table = typed_tables.get((source_name, table_name))
                contract = getattr(typed_table, "contract", None)
                landing = getattr(contract, "landing", None)
                for field in getattr(landing, "physical_columns", ()) or ():
                    native_types[field.name] = field.logical_type
            for vault in table.get("vault_entities", []) or []:
                if not vault.get("enabled", True):
                    continue
                config = entity_configs.get(vault["entity"])
                if config is None:
                    continue
                payload = set(config["payload"])
                for column in vault.get("bridge", {}).get("select", []) or []:
                    name = column.get("name")
                    if name not in payload:
                        continue
                    staging_column = _bare_source_column(column.get("expression"))
                    if staging_column is None:
                        continue
                    projected = projection.get(staging_column)
                    if projected is None:
                        continue
                    fact = _normalise_logical_type(projected.get("logical_type"))
                    if fact is None:
                        fact = _normalise_logical_type(
                            native_types.get(projected.get("source", staging_column))
                        )
                    if fact is None:
                        continue
                    observed.setdefault(vault["entity"], {}).setdefault(name, set()).add(fact)
    facts: dict[str, dict[str, str]] = {}
    for entity_name, columns in observed.items():
        agreed = {
            column: next(iter(values))
            for column, values in columns.items()
            if len(values) == 1
        }
        if agreed:
            facts[entity_name] = agreed
    return facts


def normalise_projection_expression(expression: Any) -> str:
    """Normalise formatting whitespace without changing quoted literal content.

    Expression fingerprints are safety facts, not formatting checks. Runs of whitespace
    outside SQL/Jinja string literals collapse to one space; whitespace inside single or
    double quotes remains significant. Doubled quote characters are treated as escapes.
    """
    text = str(expression).strip()
    tokens: list[str] = []
    word: list[str] = []
    index = 0

    def flush_word() -> None:
        if word:
            tokens.append("".join(word))
            word.clear()

    while index < len(text):
        character = text[index]
        if character in ("'", '"'):
            flush_word()
            quote = character
            quoted = [character]
            index += 1
            while index < len(text):
                current = text[index]
                quoted.append(current)
                if current == quote:
                    if index + 1 < len(text) and text[index + 1] == quote:
                        quoted.append(text[index + 1])
                        index += 2
                        continue
                    index += 1
                    break
                index += 1
            tokens.append("".join(quoted))
            continue
        elif character.isspace():
            flush_word()
        elif character.isalnum() or character in ("_", "$", "."):
            word.append(character)
        else:
            flush_word()
            tokens.append(character)
        index += 1
    flush_word()
    return " ".join(tokens)


def resolved_payload_expression(
    bridge_expression: Any, projection: dict[str, dict[str, Any]]
) -> str:
    """Resolve each ``source.<column>`` in a bridge payload expression to the staging
    projection expression that supplies it, then normalise the resulting text.

    Constants and resolution outputs carry their bridge expression unchanged. This is
    intentionally a small declaration-path resolver, not a SQL lineage engine.
    """
    bridge_text = str(bridge_expression)

    def replace(match: re.Match[str]) -> str:
        column = match.group(1)
        projected = projection.get(column)
        if projected is None:
            return match.group(0)
        return f"({normalise_projection_expression(projected.get('expression', ''))})"

    return normalise_projection_expression(SOURCE_COLUMN_REFERENCE_RE.sub(replace, bridge_text))


def payload_projection_facts(
    declarations: list[dict[str, Any]], entity_configs: dict[str, dict[str, Any]]
) -> dict[str, dict[str, dict[str, str]]]:
    """Return deterministic resolved-expression fingerprints by entity, payload column
    and source route.

    A route includes source, table and vault mapping because one entity can legitimately
    receive the same payload column through different source expressions. New routes are
    additive; changing an existing route's resolved expression is a redefinition.
    """
    facts: dict[str, dict[str, dict[str, str]]] = {}
    for declaration in declarations:
        source_name = declaration["source"]["name"]
        for table_name, table in (declaration.get("tables") or {}).items():
            projection = {
                column["name"]: column
                for column in table.get("projection", []) or []
                if isinstance(column, dict) and column.get("name")
            }
            for vault in table.get("vault_entities", []) or []:
                if not vault.get("enabled", True):
                    continue
                entity_name = vault["entity"]
                config = entity_configs.get(entity_name)
                if config is None:
                    continue
                payload = set(config["payload"])
                vault_name = str(vault.get("name") or entity_name)
                route = f"{source_name}.{table_name}.{vault_name}"
                for column in (vault.get("bridge") or {}).get("select", []) or []:
                    payload_column = column.get("name")
                    if payload_column not in payload:
                        continue
                    resolved = resolved_payload_expression(column.get("expression", ""), projection)
                    fingerprint = hashlib.sha256(resolved.encode("utf-8")).hexdigest()
                    routes = facts.setdefault(entity_name, {}).setdefault(payload_column, {})
                    previous = routes.get(route)
                    if previous is not None and previous != fingerprint:
                        raise ValueError(
                            f"{source_name}:{table_name}:{vault_name}: payload column "
                            f"{payload_column!r} resolves to two expressions on route {route!r}"
                        )
                    routes[route] = fingerprint
    return facts


def render_evolution_ledger(domain_name: str, entities: dict[str, dict[str, Any]]) -> str:
    """The ledger bytes for one domain: deterministic, sorted by entity, LF."""
    lines = [
        YAML_HEADER,
        f"# Evolution ledger for the {domain_name} domain. Per entity it records the payload",
        "# column roster, the hashdiff basis (the exact column set the stored hashdiffs were",
        "# computed over), the hashdiff_exclude set that basis consumed, the basis version,",
        "# and resolved projection-expression fingerprints for every payload source route.",
        "# The basis and the exclusion set together name the payload roster as it stood when the",
        "# basis froze, which is the roster the basis-conflict grade runs against. Emit grades",
        "# every later declared payload against this file: an extension enters the estate online",
        "# with the basis frozen, and a removal, a rename or a type/expression redefinition",
        "# raises an estate migration requirement.",
        "# A pending_basis_version alongside pending_hashdiff_basis and pending_hashdiff_exclude",
        "# records a re-baseline in flight: the basis the stored hashdiffs are being recomputed",
        "# over. While it stands, emit and generated stage execution stop with a named error.",
        f"version: {EVOLUTION_LEDGER_VERSION}",
        f"domain: {domain_name}",
        "entities:",
    ]
    for entity_name in sorted(entities):
        record = entities[entity_name]
        lines.append(f"  {entity_name}:")
        lines.append(f"    basis_version: {record['basis_version']}")
        for key in ("payload", "hashdiff_basis", "hashdiff_exclude"):
            columns = list(record[key])
            if columns:
                lines.append(f"    {key}:")
                lines.extend(f"    - {column}" for column in columns)
            else:
                lines.append(f"    {key}: []")
        pending = record.get("pending")
        if pending:
            lines.append(f"    pending_basis_version: {pending['basis_version']}")
            for key, rendered in (
                ("hashdiff_basis", "pending_hashdiff_basis"),
                ("hashdiff_exclude", "pending_hashdiff_exclude"),
            ):
                columns = list(pending[key])
                if columns:
                    lines.append(f"    {rendered}:")
                    lines.extend(f"    - {column}" for column in columns)
                else:
                    lines.append(f"    {rendered}: []")
            if "column_types" in pending:
                pending_types = pending.get("column_types") or {}
                if pending_types:
                    lines.append("    pending_column_types:")
                    for column in sorted(pending_types):
                        lines.append(f"      {column}: {json.dumps(pending_types[column])}")
                else:
                    lines.append("    pending_column_types: {}")
            if "projection_fingerprints" in pending:
                pending_fingerprints = pending.get("projection_fingerprints") or {}
                if pending_fingerprints:
                    lines.append("    pending_projection_fingerprints:")
                    for column in sorted(pending_fingerprints):
                        lines.append(f"      {column}:")
                        for route in sorted(pending_fingerprints[column]):
                            fingerprint = pending_fingerprints[column][route]
                            lines.append(
                                f"        {json.dumps(route)}: {json.dumps(fingerprint)}"
                            )
                else:
                    lines.append("    pending_projection_fingerprints: {}")
        types = record.get("column_types") or {}
        if types:
            lines.append("    column_types:")
            for column in sorted(types):
                lines.append(f"      {column}: {json.dumps(types[column])}")
        fingerprints = record.get("projection_fingerprints") or {}
        if fingerprints:
            lines.append("    projection_fingerprints:")
            for column in sorted(fingerprints):
                lines.append(f"      {column}:")
                for route in sorted(fingerprints[column]):
                    fingerprint = fingerprints[column][route]
                    lines.append(f"        {json.dumps(route)}: {json.dumps(fingerprint)}")
    return "\n".join(lines) + "\n"


def _load_projection_fingerprints(value: Any, where: str) -> dict[str, dict[str, str]]:
    if value in (None, {}):
        return {}
    if not isinstance(value, dict):
        raise ValueError(f"{where}: expected a mapping by payload column and source route")
    loaded: dict[str, dict[str, str]] = {}
    for column, routes in value.items():
        if not isinstance(routes, dict):
            raise ValueError(f"{where}.{column}: expected a mapping of source routes")
        loaded_routes: dict[str, str] = {}
        for route, fingerprint in routes.items():
            text = str(fingerprint)
            if re.fullmatch(r"[0-9a-f]{64}", text) is None:
                raise ValueError(
                    f"{where}.{column}.{route}: expected a lowercase SHA-256 fingerprint"
                )
            loaded_routes[str(route)] = text
        loaded[str(column)] = loaded_routes
    return loaded


def load_evolution_ledger(path: Path) -> dict[str, dict[str, Any]]:
    """Read one domain's committed ledger into per-entity records.

    A missing file reads as an empty ledger, which is what makes the first emit a
    bootstrap. A present file with a shape this emitter cannot grade against fails
    loudly, naming the file.
    """
    if not path.exists():
        return {}
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ValueError(f"{path}: expected a YAML mapping")
    version = data.get("version")
    if version not in SUPPORTED_EVOLUTION_LEDGER_VERSIONS:
        raise ValueError(
            f"{path}: ledger version {version!r} is not the version this emitter "
            f"grades against ({', '.join(str(item) for item in SUPPORTED_EVOLUTION_LEDGER_VERSIONS)})"
        )
    entities = data.get("entities") or {}
    if not isinstance(entities, dict):
        raise ValueError(f"{path}:entities: expected a mapping")
    records: dict[str, dict[str, Any]] = {}
    for entity_name, record in entities.items():
        if not isinstance(record, dict):
            raise ValueError(f"{path}:entities.{entity_name}: expected a mapping")
        payload = record.get("payload") or []
        basis = record.get("hashdiff_basis") or []
        basis_version = record.get("basis_version")
        if not isinstance(payload, list) or not isinstance(basis, list):
            raise ValueError(
                f"{path}:entities.{entity_name}: payload and hashdiff_basis are column lists"
            )
        if not isinstance(basis_version, int) or isinstance(basis_version, bool):
            raise ValueError(
                f"{path}:entities.{entity_name}: basis_version is an integer, "
                f"got {basis_version!r}"
            )
        # The exclusion set the recorded basis consumed. Grading needs it to know the
        # payload roster the basis froze over, so the key is required: every emit writes
        # it, and an empty list is the ordinary reading for a basis that excluded nothing.
        if "hashdiff_exclude" not in record:
            raise ValueError(
                f"{path}:entities.{entity_name}: hashdiff_exclude records the exclusion set "
                f"the basis consumed and is required; re-run emit to regenerate the ledger"
            )
        excluded = record.get("hashdiff_exclude") or []
        if not isinstance(excluded, list):
            raise ValueError(
                f"{path}:entities.{entity_name}: hashdiff_exclude is a column list"
            )
        types = record.get("column_types") or {}
        if not isinstance(types, dict):
            raise ValueError(f"{path}:entities.{entity_name}.column_types: expected a mapping")
        fingerprints = _load_projection_fingerprints(
            record.get("projection_fingerprints"),
            f"{path}:entities.{entity_name}.projection_fingerprints",
        )
        records[entity_name] = {
            "payload": [str(column) for column in payload],
            "hashdiff_basis": [str(column) for column in basis],
            "hashdiff_exclude": [str(column) for column in excluded],
            "basis_version": basis_version,
            "column_types": {str(key): str(value) for key, value in types.items()},
            "projection_fingerprints": fingerprints,
        }
        pending_version = record.get("pending_basis_version")
        if pending_version is not None:
            if not isinstance(pending_version, int) or isinstance(pending_version, bool):
                raise ValueError(
                    f"{path}:entities.{entity_name}: pending_basis_version is an integer, "
                    f"got {pending_version!r}"
                )
            pending_basis = record.get("pending_hashdiff_basis") or []
            pending_exclude = record.get("pending_hashdiff_exclude") or []
            if not isinstance(pending_basis, list) or not isinstance(pending_exclude, list):
                raise ValueError(
                    f"{path}:entities.{entity_name}: pending_hashdiff_basis and "
                    f"pending_hashdiff_exclude are column lists"
                )
            pending: dict[str, Any] = {
                "basis_version": pending_version,
                "hashdiff_basis": [str(column) for column in pending_basis],
                "hashdiff_exclude": [str(column) for column in pending_exclude],
            }
            if "pending_column_types" in record:
                pending_types = record.get("pending_column_types") or {}
                if not isinstance(pending_types, dict):
                    raise ValueError(
                        f"{path}:entities.{entity_name}.pending_column_types: expected a mapping"
                    )
                pending["column_types"] = {
                    str(key): str(value) for key, value in pending_types.items()
                }
            if "pending_projection_fingerprints" in record:
                pending["projection_fingerprints"] = _load_projection_fingerprints(
                    record.get("pending_projection_fingerprints"),
                    f"{path}:entities.{entity_name}.pending_projection_fingerprints",
                )
            records[entity_name]["pending"] = pending
    return records


def _grade_entity(
    entity_name: str,
    domain_name: str,
    record: dict[str, Any],
    declared_payload: list[str],
    declared_basis: list[str],
    declared_types: dict[str, str],
    declared_fingerprints: dict[str, dict[str, str]],
) -> tuple[dict[str, Any], list[str]]:
    """Grade one entity's declared payload against its ledger record.

    Returns the record the ledger now carries and the columns an extension added.
    Raises an estate migration requirement on every other change class.
    """
    ledger_payload = record["payload"]
    ledger_basis = record["hashdiff_basis"]
    ledger_exclude = record["hashdiff_exclude"]
    ledger_types = record["column_types"]
    ledger_fingerprints = record["projection_fingerprints"]

    removed = [column for column in ledger_payload if column not in declared_payload]
    added = [column for column in declared_payload if column not in ledger_payload]
    if removed and added:
        raise _estate_migration_requirement(
            entity_name,
            removed,
            "rename",
            f"keep {removed[0]!r} in the payload and add {added[0]!r} beside it as an "
            f"extension, or run a reset-class rebuild of the entity's satellites",
        )
    if removed:
        raise _estate_migration_requirement(
            entity_name,
            removed,
            "removal",
            "restore the column to the payload, or run a reset-class rebuild of the "
            "entity's satellites, which reloads their stored history",
        )

    redefined = sorted(
        column
        for column, recorded in ledger_types.items()
        if column in declared_types and declared_types[column] != recorded
    )
    if redefined:
        first = redefined[0]
        raise _estate_migration_requirement(
            entity_name,
            redefined,
            "redefinition",
            f"restore the recorded type {ledger_types[first]!r} for {first!r}, or run "
            f"`ergasterion evolve rebaseline {domain_name} {entity_name}` to adopt the "
            f"declared type {declared_types[first]!r} and recompute the stored hashdiffs",
        )

    changed_routes: list[tuple[str, str]] = []
    for column, routes in ledger_fingerprints.items():
        declared_routes = declared_fingerprints.get(column, {})
        for route, recorded in routes.items():
            current = declared_routes.get(route)
            if current is not None and current != recorded:
                changed_routes.append((column, route))
    if changed_routes:
        changed_routes.sort()
        columns = sorted({column for column, _route in changed_routes})
        first_column, first_route = changed_routes[0]
        raise _estate_migration_requirement(
            entity_name,
            columns,
            "redefinition",
            f"restore the projection expression for {first_column!r} on source route "
            f"{first_route!r}, or run `ergasterion evolve rebaseline {domain_name} "
            f"{entity_name}` to adopt the changed expression and recompute the stored "
            f"hashdiffs",
        )

    # The hashdiff basis is frozen at its recorded value, so a later hashdiff_exclude
    # edit is graded on the at-basis payload roster: the recorded basis plus the exclusion
    # set that basis consumed, which together are exactly the payload columns present when
    # the stored hashdiffs were computed. An extension's column arrived after the freeze,
    # sits outside that roster, and stays outside change detection whether or not
    # hashdiff_exclude names it -- so it grades silently on every later emit.
    at_basis_roster = list(ledger_basis) + [
        column for column in ledger_exclude if column not in ledger_basis
    ]
    basis_now = [column for column in at_basis_roster if column in declared_basis]
    if basis_now != ledger_basis:
        moved = sorted(set(basis_now) ^ set(ledger_basis)) or sorted(set(ledger_basis))
        raise _estate_migration_requirement(
            entity_name,
            moved,
            "hashdiff basis conflict",
            f"restore hashdiff_exclude to the set the recorded basis was computed over, "
            f"or run `ergasterion evolve rebaseline {domain_name} {entity_name}` to adopt "
            f"the current payload as the new hashdiff basis and recompute the stored "
            f"hashdiffs in place",
        )

    updated_types = dict(ledger_types)
    updated_types.update(declared_types)
    updated_fingerprints = {
        column: dict(routes) for column, routes in ledger_fingerprints.items()
    }
    for column, routes in declared_fingerprints.items():
        updated_fingerprints.setdefault(column, {}).update(routes)
    return (
        {
            "payload": list(declared_payload),
            "hashdiff_basis": list(ledger_basis),
            # The exclusion set stays frozen beside the basis it produced. A re-baseline
            # is the operation that adopts a new basis and a new exclusion set together.
            "hashdiff_exclude": list(ledger_exclude),
            "basis_version": record["basis_version"],
            "column_types": updated_types,
            "projection_fingerprints": updated_fingerprints,
        },
        added,
    )


def grade_estate_evolution(
    domain: dict[str, Any],
    declarations: list[dict[str, Any]],
    *,
    ctx: EstateContext | None = None,
    typed: Any | None = None,
) -> tuple[list[GeneratedFile], list[str]]:
    """Grade every entity's declared payload against its domain's evolution ledger,
    freeze each entity's hashdiff basis at the recorded value, and return the ledger
    files to write alongside the notices emit prints.

    On the first emit for a domain the ledger bootstraps: the recorded basis equals the
    hashdiff set the loader derives, so every already-generated file stays byte-identical
    and ``hashdiff_exclude`` is consumed exactly once, at that bootstrap.
    """
    ctx = ctx or _DEFAULT_CTX
    entity_configs = domain["entity_configs"]
    exclusions = domain.get("hashdiff_exclude", {}) or {}
    entity_domains = domain.get("entity_domains", {}) or {}
    type_facts = payload_type_facts(declarations, entity_configs, typed)
    projection_facts = payload_projection_facts(declarations, entity_configs)

    by_domain: dict[str, list[str]] = {}
    for entity_name in entity_configs:
        by_domain.setdefault(entity_domains.get(entity_name, "domain"), []).append(entity_name)

    files: list[GeneratedFile] = []
    notices: list[str] = []
    for domain_name in sorted(by_domain):
        path = evolution_ledger_path(domain_name, ctx=ctx)
        ledger = load_evolution_ledger(path)
        # The pending gate. A re-baseline in flight has the ledger and the warehouse
        # disagreeing about the basis the stored hashdiffs were computed over, so emit
        # stops before it can regenerate a stage model against either one.
        pending_entries = [
            (entity_name, record)
            for entity_name, record in sorted(ledger.items())
            if record.get("pending")
        ]
        if pending_entries:
            raise _pending_rebaseline_requirement(domain_name, pending_entries)
        records: dict[str, dict[str, Any]] = {}
        bootstrapped: list[str] = []
        for entity_name in sorted(by_domain[domain_name]):
            config = entity_configs[entity_name]
            declared_payload = list(config["payload"])
            exclude = exclusions.get(entity_name, set())
            declared_basis = [
                column for column in declared_payload if column not in exclude
            ]
            # The two halves of the declared payload roster: the basis and the exclusion
            # set that produced it. The bootstrap records both, so a later emit can name
            # the roster the basis froze over without depending on the payload roster the
            # ledger carries by then.
            declared_exclude = [
                column for column in declared_payload if column in exclude
            ]
            declared_types = dict(type_facts.get(entity_name, {}))
            declared_fingerprints = {
                column: dict(routes)
                for column, routes in projection_facts.get(entity_name, {}).items()
            }
            record = ledger.get(entity_name)
            if record is None:
                records[entity_name] = {
                    "payload": declared_payload,
                    "hashdiff_basis": declared_basis,
                    "hashdiff_exclude": declared_exclude,
                    "basis_version": 1,
                    "column_types": declared_types,
                    "projection_fingerprints": declared_fingerprints,
                }
                bootstrapped.append(entity_name)
            else:
                updated, added = _grade_entity(
                    entity_name,
                    domain_name,
                    record,
                    declared_payload,
                    declared_basis,
                    declared_types,
                    declared_fingerprints,
                )
                records[entity_name] = updated
                if added:
                    notices.append(
                        f"estate evolution: extension on {domain_name}.{entity_name} adds "
                        f"{', '.join(added)}; {'these columns stay' if len(added) > 1 else 'this column stays'} "
                        f"outside change detection until "
                        f"`ergasterion evolve rebaseline {domain_name} {entity_name}` runs"
                    )
            config["hashed_columns"][config["hashdiff"]]["columns"] = list(
                records[entity_name]["hashdiff_basis"]
            )
        if bootstrapped:
            notices.append(
                f"estate evolution: ledger bootstrapped for {domain_name} with the derived "
                f"hashdiff basis of {len(bootstrapped)} entity(ies): {', '.join(bootstrapped)}"
            )
        files.append(GeneratedFile(path, render_evolution_ledger(domain_name, records)))
    return files, notices


# ---------------------------------------------------------------------------
# The declared re-baseline.
#
# A re-baseline adopts the current payload as the new hashdiff basis and recomputes the
# stored hashdiffs in place. It runs in two phases over a committed pending basis,
# because the ledger file and the warehouse share no transaction:
#
#   phase one   record the pending basis -- first in the warehouse, so the fail-closed
#               gate stands from that moment, then in the evolution ledger.
#   phase two   run the adapter-dispatched migration operation (a dbt run-operation)
#               that adds any missing satellite columns and recomputes every stored
#               hashdiff from the stored payload under the pending basis, verify it with
#               the golden-hash parity spot check, write the audit row, and promote the
#               pending basis to active in the ledger. The warehouse marker deliberately
#               remains until regenerated models are deployed and the operator clears it.
#
# Every step is idempotent and the warehouse marker outlives the ledger record on both
# sides, so an interruption at any boundary either blocks the next build with the named
# error or converges on a re-run.
# ---------------------------------------------------------------------------

# The line the migration operation logs its JSON outcome on.
REBASELINE_RESULT_MARKER = "DPF_REBASELINE_RESULT="

# The macros in macros/estate_evolution.sql the CLI drives.
REBASELINE_BEGIN_MACRO = "dpf_evolve_rebaseline_begin"
REBASELINE_REWRITE_MACRO = "dpf_evolve_rebaseline_rewrite"
REBASELINE_CLEAR_MACRO = "dpf_evolve_rebaseline_clear"
REBASELINE_STATUS_MACRO = "dpf_evolve_rebaseline_status"

_ANSI_RE = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")


def resolve_dbt_executable(declared: str | None = None) -> str:
    """The dbt executable the migration operation runs under.

    Resolution order: the declared path, the DPF_DBT environment variable, the running
    interpreter's own script directory (so a virtual environment's dbt is preferred over
    whatever sits earlier on PATH), then PATH.
    """
    for candidate in (declared, os.environ.get("DPF_DBT")):
        if candidate:
            return candidate
    interpreter_dir = Path(sys.executable).resolve().parent
    for name in ("dbt.exe", "dbt"):
        candidate_path = interpreter_dir / name
        if candidate_path.is_file():
            return str(candidate_path)
    found = shutil.which("dbt")
    if found:
        return found
    raise ValueError(
        "no dbt executable found for the re-baseline migration operation; pass --dbt PATH "
        "or set DPF_DBT"
    )


class DbtRunOperation:
    """Runs one macro from macros/estate_evolution.sql as a dbt run-operation and returns
    the JSON outcome it logs.

    The CLI holds this behind an injectable seam so the phase functions can be driven
    directly by a test that proves a crash boundary without a subprocess.
    """

    marker = REBASELINE_RESULT_MARKER

    def __init__(
        self,
        *,
        project_dir: Path,
        profiles_dir: Path | None = None,
        target: str | None = None,
        executable: str | None = None,
        echo: bool = False,
        env: dict[str, str] | None = None,
        marker: str | None = None,
    ) -> None:
        self.project_dir = Path(project_dir)
        self.profiles_dir = Path(profiles_dir) if profiles_dir else None
        self.target = target
        self.executable = resolve_dbt_executable(executable)
        self.echo = echo
        self.env = env
        if marker is not None:
            self.marker = marker

    def command(self, macro: str, payload: dict[str, Any]) -> list[str]:
        command = [
            self.executable,
            "--no-use-colors",
            "run-operation",
            macro,
            "--args",
            json.dumps({"payload": payload}, sort_keys=True),
            "--project-dir",
            str(self.project_dir),
        ]
        if self.profiles_dir is not None:
            command += ["--profiles-dir", str(self.profiles_dir)]
        if self.target:
            command += ["-t", self.target]
        return command

    def __call__(self, macro: str, payload: dict[str, Any]) -> dict[str, Any]:
        command = self.command(macro, payload)
        completed = subprocess.run(
            command,
            cwd=str(self.project_dir),
            env=self.env,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
        output = _ANSI_RE.sub("", f"{completed.stdout}\n{completed.stderr}")
        if self.echo:
            print(output.strip())
        if completed.returncode != 0:
            tail = "\n".join(output.strip().splitlines()[-25:])
            raise RuntimeError(
                f"dbt run-operation {macro} failed with exit code {completed.returncode}:\n{tail}"
            )
        return parse_rebaseline_result(output, macro, marker=self.marker)


def parse_rebaseline_result(
    output: str, macro: str, *, marker: str = REBASELINE_RESULT_MARKER
) -> dict[str, Any]:
    """The JSON outcome an operation logged, read from a dbt run's output."""
    for line in reversed(_ANSI_RE.sub("", output).splitlines()):
        index = line.find(marker)
        if index >= 0:
            return json.loads(line[index + len(marker) :].strip())
    raise RuntimeError(
        f"dbt run-operation {macro} logged no {marker} line; the operation did not reach "
        f"its own result"
    )


def rebaseline_plan(
    domain_name: str, entity_name: str, *, ctx: EstateContext | None = None
) -> dict[str, Any]:
    """Everything one entity's re-baseline needs, read from the declarations and the
    ledger: the new hashdiff basis, both basis versions, and the satellite relations that
    carry the entity's stored history beside the stage relation each one is built from.

    A pending record already in the ledger owns the basis: phase two adopts exactly what
    phase one recorded, so declarations that moved in between leave it where it was.
    """
    ctx = ctx or _DEFAULT_CTX
    domain = load_domains(ctx=ctx)
    entity_configs = domain["entity_configs"]
    if entity_name not in entity_configs:
        raise ValueError(
            f"estate evolution: unknown entity {entity_name!r}; the declared entities are "
            f"{', '.join(sorted(entity_configs))}"
        )
    recorded_domain = (domain.get("entity_domains") or {}).get(entity_name)
    if recorded_domain != domain_name:
        raise ValueError(
            f"estate evolution: entity {entity_name!r} belongs to domain "
            f"{recorded_domain!r}, not {domain_name!r}"
        )
    config = entity_configs[entity_name]
    declared_payload = list(config["payload"])
    declared_basis = list(config["hashed_columns"][config["hashdiff"]]["columns"])

    declarations = load_declarations(domain, ctx=ctx)
    typed = load_typed_declarations(ctx)
    declared_types = dict(
        payload_type_facts(declarations, entity_configs, typed).get(entity_name, {})
    )
    declared_fingerprints = {
        column: dict(routes)
        for column, routes in payload_projection_facts(
            declarations, entity_configs
        ).get(entity_name, {}).items()
    }
    satellites: list[dict[str, str]] = []
    for declaration in declarations:
        for table in declaration.get("tables", {}).values():
            for vault in table.get("vault_entities", []) or []:
                if vault["entity"] != entity_name or not vault.get("enabled", True):
                    continue
                satellites.append(
                    {"satellite": vault["satellite_model"], "stage": vault["stage_model"]}
                )
    if not satellites:
        raise ValueError(
            f"estate evolution: entity {entity_name!r} has no enabled satellite, so there "
            f"is no stored history to re-baseline"
        )

    path = evolution_ledger_path(domain_name, ctx=ctx)
    ledger = load_evolution_ledger(path)
    record = ledger.get(entity_name)
    if record is None:
        raise ValueError(
            f"{path}: no ledger record for {entity_name!r}; run `ergasterion emit` to "
            f"bootstrap the evolution ledger before a re-baseline"
        )
    pending = record.get("pending")
    if pending:
        basis = list(pending["hashdiff_basis"])
        exclude = list(pending["hashdiff_exclude"])
        basis_version = pending["basis_version"]
        adopted_types = dict(pending.get("column_types", declared_types))
        adopted_fingerprints = {
            column: dict(routes)
            for column, routes in pending.get(
                "projection_fingerprints", declared_fingerprints
            ).items()
        }
    else:
        basis = declared_basis
        exclude = [column for column in declared_payload if column not in declared_basis]
        basis_version = record["basis_version"] + 1
        adopted_types = declared_types
        adopted_fingerprints = declared_fingerprints
    return {
        "domain": domain_name,
        "entity": entity_name,
        "hashdiff": config["hashdiff"],
        "payload": declared_payload,
        "basis": basis,
        "hashdiff_exclude": exclude,
        "column_types": adopted_types,
        "projection_fingerprints": adopted_fingerprints,
        "basis_version": basis_version,
        "previous_basis_version": record["basis_version"],
        "active_basis": list(record["hashdiff_basis"]),
        "satellites": satellites,
        "pending": bool(pending),
        "ledger_path": path,
    }


def rebaseline_payload(
    plan: dict[str, Any],
    *,
    basis: list[str] | None = None,
    satellites: list[str] | None = None,
    spot_check_rows: int = 1000,
) -> dict[str, Any]:
    """The argument the migration operation reads. ``basis`` names the column set the
    recompute hashes over, and ``satellites`` narrows the rewrite to named relations, the
    seam a resumed rewrite uses."""
    chosen = plan["satellites"]
    if satellites is not None:
        wanted = set(satellites)
        known = {pair["satellite"] for pair in plan["satellites"]}
        unknown = sorted(wanted - known)
        if unknown:
            raise ValueError(
                f"estate evolution: {', '.join(unknown)} is not a satellite of "
                f"{plan['entity']!r}; its satellites are {', '.join(sorted(known))}"
            )
        chosen = [pair for pair in plan["satellites"] if pair["satellite"] in wanted]
    return {
        "entity": plan["entity"],
        "domain": plan["domain"],
        "hashdiff": plan["hashdiff"],
        "basis": list(plan["basis"] if basis is None else basis),
        "basis_version": plan["basis_version"],
        "previous_basis_version": plan["previous_basis_version"],
        "satellites": chosen,
        "spot_check_rows": spot_check_rows,
    }


def _rewrite_ledger(path: Path, records: dict[str, dict[str, Any]], domain_name: str) -> None:
    content = render_evolution_ledger(domain_name, records)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content.encode("utf-8"))


def ledger_record_pending(plan: dict[str, Any]) -> None:
    """Phase one's ledger half: record the pending basis beside the active one."""
    path = plan["ledger_path"]
    records = load_evolution_ledger(path)
    records[plan["entity"]]["pending"] = {
        "basis_version": plan["basis_version"],
        "hashdiff_basis": list(plan["basis"]),
        "hashdiff_exclude": list(plan["hashdiff_exclude"]),
        "column_types": dict(plan["column_types"]),
        "projection_fingerprints": {
            column: dict(routes)
            for column, routes in plan["projection_fingerprints"].items()
        },
    }
    _rewrite_ledger(path, records, plan["domain"])


def ledger_promote_pending(plan: dict[str, Any]) -> bool:
    """Phase two's ledger half: the pending basis becomes the active one. Returns whether
    a pending record was there to promote, so a converging re-run stays silent."""
    path = plan["ledger_path"]
    records = load_evolution_ledger(path)
    record = records[plan["entity"]]
    pending = record.pop("pending", None)
    if pending is None:
        return False
    record["hashdiff_basis"] = list(pending["hashdiff_basis"])
    record["hashdiff_exclude"] = list(pending["hashdiff_exclude"])
    record["basis_version"] = pending["basis_version"]
    if "column_types" in pending:
        record["column_types"] = dict(pending["column_types"])
    if "projection_fingerprints" in pending:
        record["projection_fingerprints"] = {
            column: dict(routes)
            for column, routes in pending["projection_fingerprints"].items()
        }
    _rewrite_ledger(path, records, plan["domain"])
    return True


def ledger_demote_pending(plan: dict[str, Any]) -> bool:
    """An abort's ledger half: the pending basis goes, the active one stands."""
    path = plan["ledger_path"]
    records = load_evolution_ledger(path)
    if records[plan["entity"]].pop("pending", None) is None:
        return False
    _rewrite_ledger(path, records, plan["domain"])
    return True


def rebaseline_begin(
    plan: dict[str, Any], runner: Any, *, spot_check_rows: int = 1000
) -> dict[str, Any]:
    """Phase one. The warehouse marker lands first, so the fail-closed build gate stands
    from the first moment a re-baseline exists; the ledger record follows."""
    payload = rebaseline_payload(plan, spot_check_rows=spot_check_rows)
    outcome = runner(REBASELINE_BEGIN_MACRO, payload)
    ledger_record_pending(plan)
    return outcome


def rebaseline_rewrite(
    plan: dict[str, Any],
    runner: Any,
    *,
    basis: list[str] | None = None,
    satellites: list[str] | None = None,
    spot_check_rows: int = 1000,
) -> dict[str, Any]:
    """Phase two's warehouse half: add any missing satellite columns, recompute every
    stored hashdiff from the stored payload under the given basis, verify the rewrite with
    the golden-hash parity spot check, and write the audit row."""
    payload = rebaseline_payload(
        plan, basis=basis, satellites=satellites, spot_check_rows=spot_check_rows
    )
    return runner(REBASELINE_REWRITE_MACRO, payload)


def rebaseline_clear(plan: dict[str, Any], runner: Any) -> dict[str, Any]:
    """Drop the warehouse marker. The ledger is the authority, so this closes the
    operation after the ledger has been promoted or demoted."""
    return runner(REBASELINE_CLEAR_MACRO, {"entity": plan["entity"], "domain": plan["domain"]})


def rebaseline_status(plan: dict[str, Any], runner: Any) -> list[dict[str, Any]]:
    """The pending markers the warehouse carries."""
    outcome = runner(REBASELINE_STATUS_MACRO, {"entity": plan["entity"], "domain": plan["domain"]})
    return list(outcome.get("pending") or [])


def window_audit_plan(
    source_name: str, table_name: str, *, ctx: EstateContext | None = None, sample: int = 20
) -> dict[str, Any]:
    """Everything the audit invocation needs to scan the full source for one declared
    table: the window the run applies, the table-local satellite layout the floor is
    resolved from, the landing relation the full source lives in, and the landing columns
    behind the derived key and the effective column.
    """
    ctx = ctx or _DEFAULT_CTX
    domain = load_domains(ctx=ctx)
    declarations = load_declarations(domain, ctx=ctx)
    for declaration in declarations:
        source = declaration["source"]
        if source["name"] != source_name:
            continue
        table = (declaration.get("tables") or {}).get(table_name)
        if table is None:
            raise ValueError(
                f"estate evolution: source {source_name!r} declares no table "
                f"{table_name!r}; its tables are "
                f"{', '.join(sorted(declaration.get('tables') or {}))}"
            )
        block = table.get(STAGING_INCREMENT_KEY)
        if not block:
            raise ValueError(
                f"estate evolution: {source_name}.{table_name} declares no "
                f"{STAGING_INCREMENT_KEY}, so it processes every row on every run and has "
                f"no window to audit"
            )
        where = f"{source.get('declaration_file', source_name)}:{table_name}"
        effective_column = derive_effective_column(table, where)
        watermark = source_satellite_layout(
            declaration, table_name, source.get("declaration_file", source_name)
        )
        expressions = {
            column["name"]: column.get("expression")
            for column in table.get("projection", []) or []
            if isinstance(column, dict) and "name" in column
        }
        natural_key = list(table.get(NATURAL_KEY_FIELD) or [])
        landing_key = [
            landing_column_for(expressions.get(column), where, column)
            for column in natural_key
        ]
        landing_effective = landing_column_for(
            expressions.get(effective_column), where, effective_column
        )
        landing = table["landing"]
        if landing["kind"] == "source":
            landing_reference = {
                "kind": "source",
                "source_name": landing["source_name"],
                "identifier": landing["identifier"],
            }
        else:
            landing_reference = {"kind": "model", "model": table["raw_model"]}
        return {
            "source": source_name,
            "table": table_name,
            "effective_column": effective_column,
            "lookback_minutes": block["lookback_minutes"],
            "watermark": watermark,
            "landing": landing_reference,
            "landing_key": landing_key,
            "landing_effective_column": landing_effective,
            "sample": sample,
        }
    raise ValueError(
        f"estate evolution: no declaration for source {source_name!r}; the declared sources "
        f"are {', '.join(sorted(item['source']['name'] for item in declarations))}"
    )


