# The macro the audit invocation drives.
WINDOW_AUDIT_MACRO = "dpf_window_audit"

# A bridge payload expression can refer to one or more staging projection columns. The
# evolution ledger fingerprints the resolved expression, so changing either half of that
# path fails before a build can replay stored history under a different hashdiff.
SOURCE_COLUMN_REFERENCE_RE = re.compile(r"\bsource\.([A-Za-z_][A-Za-z0-9_]*)\b")

# AutomateDV's marker for a derived column that is a constant rather than a column
# reference. A declared record source carries it, and AutomateDV writes the text after it
# into the satellite, so that text is the literal a watermark predicate binds to.
AUTOMATE_DV_CONSTANT_PREFIX = "!"

# The landing column one staging projection expression reads. The audit invocation scans
# the full source, which is the landing relation, so it needs the landing column behind
# each derived key member and behind the effective column. Three shapes carry exactly one
# landing column: a bare column, a cast of one, and a macro call whose first argument
# names one. Anything else is an expression the audit cannot follow, and it fails there
# with a named error rather than reporting a key set it derived from the wrong column.
LANDING_BARE_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
LANDING_CAST_RE = re.compile(
    r"^cast\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s+as\s+[^()]+\)$", re.IGNORECASE
)
LANDING_MACRO_RE = re.compile(
    r"^\{\{\s*[A-Za-z_][A-Za-z0-9_.]*\(\s*'([A-Za-z_][A-Za-z0-9_]*)'.*\)\s*\}\}$"
)

# Declared values that land in SQL identifier or ref() positions must be plain
# identifiers. Anything else -- quotes, braces, spaces, path separators -- would
# render into the emitted file as live template text or broken SQL, so the gate
# rejects it at declaration load with the file and field named.
IDENTIFIER_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _require_identifier(value: Any, where: str) -> None:
    if not isinstance(value, str) or not IDENTIFIER_RE.match(value):
        raise ValueError(
            f"{where}: {value!r} must be a plain identifier "
            f"(letters, digits, underscores, starting with a letter or underscore) -- "
            f"it renders into a SQL identifier or ref() position"
        )


def _derive_hashdiff_columns(
    entity_configs: dict[str, dict[str, Any]],
    exclusions: dict[str, set[str]],
) -> None:
    """Populate each entity's hashdiff column list in place: payload minus its
    declared exclusion set. The hashdiff column list is derived from the payload
    SSOT rather than hand-listed in the domain config, so it can never silently
    diverge from the payload by a stray edit. A domain declares only the
    per-entity exclusion set (hashdiff_exclude); the default (empty set) makes the
    hashdiff every payload column.

    This derivation is the bootstrap input for the evolution ledger. Once a domain's
    ledger exists, grade_estate_evolution overwrites this list with the recorded
    hashdiff basis, so the stored hashdiffs keep matching after a later extension.
    """
    for entity_name, config in entity_configs.items():
        payload = config["payload"]
        exclude = exclusions.get(entity_name, set())
        unknown = exclude - set(payload)
        if unknown:
            raise ValueError(
                f"hashdiff_exclude[{entity_name!r}] names column(s) not in its payload: "
                f"{', '.join(sorted(unknown))}"
            )
        hashdiff_key = config["hashdiff"]
        config["hashed_columns"][hashdiff_key]["columns"] = [
            column for column in payload if column not in exclude
        ]


class EstateMigrationRequirement(ValueError):
    """The named, fail-closed error a non-additive estate change raises.

    Estate evolution absorbs an extension (new payload columns only) online. Every
    other payload change -- a removal, a rename, a redefinition, or an edit to the
    frozen hashdiff basis -- needs an act on the warehouse itself, so emit stops here
    and names the entity, the column, the change class and the remedy.
    """


class PendingReBaselineRequirement(ValueError):
    """The named, fail-closed error a pending re-baseline raises.

    A re-baseline runs in two phases over a committed pending basis, and between them
    the ledger and the warehouse disagree about which column set the stored hashdiffs
    were computed over. While the pending record stands, emit stops here and every
    generated build stops at the same gate in macros/estate_evolution.sql. The error
    names the entity, both basis versions, and the two remedies: complete the
    re-baseline, or abort it.
    """


def _pending_rebaseline_requirement(
    domain_name: str, entries: list[tuple[str, dict[str, Any]]]
) -> PendingReBaselineRequirement:
    named = ", ".join(
        f"{domain_name}.{entity} (basis version {record['basis_version']} -> "
        f"{record['pending']['basis_version']})"
        for entity, record in entries
    )
    first = entries[0][0]
    return PendingReBaselineRequirement(
        f"estate evolution: pending re-baseline on {named} blocks emit and generated "
        f"stage execution -- complete it with `ergasterion evolve rebaseline "
        f"{domain_name} {first} --complete`, or abort it with `ergasterion evolve "
        f"rebaseline {domain_name} {first} --abort`"
    )


def _estate_migration_requirement(
    entity: str, columns: list[str], change_class: str, remedy: str
) -> EstateMigrationRequirement:
    named = ", ".join(columns)
    return EstateMigrationRequirement(
        f"estate migration requirement: entity {entity!r}, column {named}, "
        f"change class {change_class!r} -- remedy: {remedy}"
    )


