def _audit_window_main(args: argparse.Namespace) -> int:
    """`ergasterion evolve audit-window <source> <table>`.

    A normal run scans nothing outside the window, so a key whose rows all fall below the
    floor is invisible to it. This invocation is the periodic check that finds those keys.
    """
    ctx = EstateContext.resolve(estate_root=args.estate_root)
    project_dir = args.project_dir or ctx.root
    try:
        payload = window_audit_plan(args.source, args.table, ctx=ctx, sample=args.sample)
        runner = DbtRunOperation(
            project_dir=project_dir,
            profiles_dir=args.profiles_dir,
            target=args.target,
            executable=args.dbt,
            echo=not args.quiet,
            marker=WINDOW_AUDIT_RESULT_MARKER,
        )
    except ValueError as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 2
    try:
        outcome = runner(WINDOW_AUDIT_MACRO, payload)
    except (ValueError, RuntimeError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 1
    print(
        f"staging increment audit of {args.source}.{args.table}: window floor "
        f"{outcome['floor']} on {outcome['effective_column']}; "
        f"{outcome['keys_outside_window']} of {outcome['keys_total']} key(s) sit wholly "
        f"outside the window"
    )
    for entry in outcome.get("sample") or []:
        columns = ", ".join(
            f"{name}={value}" for name, value in entry.items() if name != "max_effective"
        )
        print(f"  {columns} (latest effective time {entry['max_effective']})")
    if outcome["keys_outside_window"]:
        print(
            "remedy: widen the lookback for one run, or run a bounded backfill over the "
            "keys above"
        )
    return 0


def evolve_main(argv: list[str] | None = None) -> int:
    """`ergasterion evolve rebaseline <domain> <entity>` and
    `ergasterion evolve audit-window <source> <table>`."""
    args = _evolve_parser().parse_args(list(sys.argv[1:] if argv is None else argv))
    if args.operation == "audit-window":
        return _audit_window_main(args)
    ctx = EstateContext.resolve(estate_root=args.estate_root)
    project_dir = args.project_dir or ctx.root
    try:
        plan = rebaseline_plan(args.domain, args.entity, ctx=ctx)
        runner = DbtRunOperation(
            project_dir=project_dir,
            profiles_dir=args.profiles_dir,
            target=args.target,
            executable=args.dbt,
            echo=not args.quiet,
        )
    except ValueError as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 2

    label = f"{args.domain}.{args.entity}"
    try:
        if args.clear:
            if plan["pending"]:
                print(
                    f"FAIL: {label} still carries a pending basis; complete the rewrite and "
                    f"promotion before releasing the warehouse gate",
                    file=sys.stderr,
                )
                return 2
            markers = [
                marker
                for marker in rebaseline_status(plan, runner)
                if marker.get("entity") == args.entity
                and marker.get("domain") == args.domain
            ]
            if not markers:
                print(
                    f"FAIL: no warehouse re-baseline gate stands for {label}",
                    file=sys.stderr,
                )
                return 2
            rebaseline_clear(plan, runner)
            print(
                f"estate evolution: warehouse build gate released for {label}; "
                f"basis version {plan['previous_basis_version']} is active"
            )
            return 0

        if args.abort:
            if not plan["pending"]:
                print(
                    f"FAIL: {label} has no pending basis to abort; if its rewrite was already "
                    f"promoted, deploy the regenerated models and use --clear",
                    file=sys.stderr,
                )
                return 2
            demoted = ledger_demote_pending(plan)
            outcome = rebaseline_rewrite(
                plan,
                runner,
                basis=plan["active_basis"],
                satellites=args.satellite,
                spot_check_rows=args.spot_check_rows,
            )
            rebaseline_clear(plan, runner)
            print(
                f"estate evolution: re-baseline of {label} aborted; "
                f"{'the pending basis was demoted and ' if demoted else ''}"
                f"{outcome['rows_rewritten']} row(s) were rewritten back to basis version "
                f"{plan['previous_basis_version']}"
            )
            return 0

        if not args.complete:
            if plan["pending"]:
                print(
                    f"estate evolution: {label} already carries a pending basis "
                    f"(version {plan['basis_version']}); continuing with phase two"
                )
            else:
                rebaseline_begin(plan, runner, spot_check_rows=args.spot_check_rows)
                print(
                    f"estate evolution: pending basis version {plan['basis_version']} "
                    f"recorded for {label}; emit and generated stage execution stop until this "
                    f"re-baseline completes or aborts"
                )
            if args.begin:
                return 0

        if args.complete and not plan["pending"]:
            markers = [
                marker
                for marker in rebaseline_status(plan, runner)
                if marker.get("entity") == args.entity
                and marker.get("domain") == args.domain
            ]
            if not markers:
                print(
                    f"FAIL: no pending re-baseline for {label}; start one with "
                    f"`ergasterion evolve rebaseline {args.domain} {args.entity}`",
                    file=sys.stderr,
                )
                return 2
            print(
                f"estate evolution: the ledger already carries basis version "
                f"{plan['previous_basis_version']} for {label} as active; the warehouse "
                f"gate remains closed. Run `ergasterion emit`, deploy the regenerated "
                f"models, then release it with `ergasterion evolve rebaseline "
                f"{args.domain} {args.entity} --clear`"
            )
            return 0

        outcome = rebaseline_rewrite(
            plan,
            runner,
            satellites=args.satellite,
            spot_check_rows=args.spot_check_rows,
        )
        promoted = ledger_promote_pending(plan)
        print(
            f"estate evolution: warehouse rewrite of {label} complete; "
            f"{outcome['rows_rewritten']} stored hashdiff(s) recomputed under basis version "
            f"{plan['basis_version']}"
            + ("" if promoted else " (the ledger already carried it as active)")
        )
        print(
            f"estate evolution: the warehouse build gate remains closed. Run "
            f"`ergasterion emit`, deploy the regenerated models, then release it with "
            f"`ergasterion evolve rebaseline {args.domain} {args.entity} --clear`"
        )
        return 0
    except (ValueError, RuntimeError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 1


def load_domains(domains_dir: Path | None = None, *, ctx: EstateContext | None = None) -> dict[str, Any]:
    """Load and merge every per-domain model config in ``domains_dir``.

    Each domains/*.yml carries the closed vocabulary for one example domain
    (entity_configs / hashdiff_exclude / hub_configs / link_configs / bv_configs /
    res_configs). The engine itself holds no domain nouns: this loader is the single
    seam through which a domain's entities reach the templates. All domain files are
    merged into one config; two domains must not share a key in any section (a
    collision fails loudly rather than silently shadowing one behind the other). A
    second domain is therefore onboarded by DATA alone -- drop a sibling
    domains/<name>.yml plus its declarations, with zero change to this module (the
    fixture-domain test in tests/python/test_emit.py pins that guarantee).

    hashdiff_exclude values are declared as lists and used as sets; each entity's
    hashdiff column list is DERIVED here (payload minus its exclusion set), never
    hand-listed in the domain file.

    Caveat for any model-schema file a declaration references via canonical_mappings
    (the optional --openim-root hook): parse_model_attribute_schema binds only the
    FIRST '## Attribute schema' table per file -- keep exactly one such table per file.
    """
    if domains_dir is None:
        domains_dir = (ctx or _DEFAULT_CTX).domains_dir
    merged: dict[str, dict[str, Any]] = {section: {} for section in DOMAIN_SECTIONS}
    # Which domain file each entity came from. Entity keys are unique across domains
    # (the collision check below), so the mapping is one-to-one, and it is what routes
    # an entity to its own declarations/evolution/<domain>.lock.yml.
    entity_domains: dict[str, str] = {}
    files = sorted(domains_dir.glob("*.yml"))
    if not files:
        raise ValueError(f"No domain model config found in {domains_dir}")
    for path in files:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            raise ValueError(f"{path}: expected a YAML mapping")
        for entity_name in (data.get("entity_configs", {}) or {}):
            entity_domains[entity_name] = path.stem
        for section in DOMAIN_SECTIONS:
            block = data.get(section, {}) or {}
            if not isinstance(block, dict):
                raise ValueError(f"{path}:{section}: expected a mapping")
            for key, value in block.items():
                if key in merged[section]:
                    raise ValueError(
                        f"{path}: {section} key {key!r} collides with an already-loaded "
                        f"domain; domains must not share {section} keys"
                    )
                merged[section][key] = value
    merged["hashdiff_exclude"] = {
        entity: set(columns) for entity, columns in merged["hashdiff_exclude"].items()
    }
    merged["entity_domains"] = entity_domains
    _derive_hashdiff_columns(merged["entity_configs"], merged["hashdiff_exclude"])
    return merged


def validate_bv_rules_subset_of_payload(
    bv_configs: dict[str, dict[str, Any]],
    entity_configs: dict[str, dict[str, Any]],
) -> None:
    """Emit-time gate: BV_CONFIGS[entity]['rules'] keys must be a subset of that
    entity's payload columns. 'rules' is a third independent enumeration of the
    entity's column set (alongside payload and hashdiff) -- this keeps it
    honest against the payload SSOT instead of silently drifting. Fails
    loudly, naming both the entity and the offending keys.

    Parameterised (rather than reading the module globals directly) so the
    failure path is directly testable with an injected, deliberately-broken
    bv_configs/entity_configs pair.
    """
    for entity_name, bv in bv_configs.items():
        if entity_name not in entity_configs:
            raise ValueError(f"BV_CONFIGS names unknown entity {entity_name!r}")
        payload_columns = set(entity_configs[entity_name]["payload"])
        offending = sorted(set(bv["rules"]) - payload_columns)
        if offending:
            raise ValueError(
                f"BV_CONFIGS[{entity_name!r}]['rules'] keys not in {entity_name!r} payload: "
                f"{', '.join(offending)}"
            )


def validate_domain_paths(domain: dict[str, Any]) -> None:
    """Emit-time gate: every declared model path stays inside the estate's models/
    tree. A path that is absolute, carries a ``..`` segment, or sits outside
    ``models/`` would land a generated file where the project's layer config no
    longer governs its materialisation (dbt's default of view applies there), or
    outside the estate entirely. The path stem is the emitted relation's
    identifier and follows the identifier shape."""
    for section in ("hub_configs", "link_configs", "bv_configs", "res_configs"):
        for name, config in domain.get(section, {}).items():
            declared = config.get("path")
            where = f"{section}.{name}.path"
            if not isinstance(declared, str) or not declared:
                raise ValueError(f"{where}: a declared model path is required")
            posix = declared.replace("\\", "/")
            parts = posix.split("/")
            if posix.startswith("/") or (len(parts[0]) == 2 and parts[0][1] == ":"):
                raise ValueError(f"{where}: {declared!r} must be estate-relative")
            if ".." in parts:
                raise ValueError(f"{where}: {declared!r} must not carry a '..' segment")
            if parts[0] != "models":
                raise ValueError(
                    f"{where}: {declared!r} must sit under models/ so the layer's "
                    f"materialisation config governs it"
                )
            _require_identifier(Path(posix).stem, where)


def validate_res_configs(
    res_configs: dict[str, Any], *, ctx: EstateContext | None = None
) -> None:
    """Emit-time gate: entity-resolution config values that shape the emitted
    statement are validated before render. ``merge_iterations`` unrolls one pair
    of CTEs per round, so a non-integer, zero, or negative value renders broken
    or silently degraded SQL that dialect lint and a parse both accept. A
    declared ``convergence_test`` names the estate test that proves the round
    count suffices, so a dangling name fails here rather than proving nothing."""
    ctx = ctx or _DEFAULT_CTX
    for entity, res in res_configs.items():
        if res.get("transitive_merge"):
            iterations = res.get("merge_iterations")
            if not isinstance(iterations, int) or isinstance(iterations, bool) or iterations < 1:
                raise ValueError(
                    f"res_configs.{entity}: transitive_merge requires merge_iterations "
                    f"to be an integer of at least 1, got {iterations!r}"
                )
        convergence_test = res.get("convergence_test")
        if convergence_test is not None:
            test_path = ctx.root / str(convergence_test)
            if not test_path.is_file():
                raise ValueError(
                    f"res_configs.{entity}: convergence_test {convergence_test!r} "
                    f"does not exist under the estate root"
                )


def validate_unique_source_priorities(declarations: list[dict[str, Any]]) -> None:
    """Emit-time gate: enabled sources feeding an entity must have unique priorities.

    Survivorship consumes the ordered vault list emitted by ``select_vaults``. A
    shared priority would leave source name as an undeclared tiebreaker, allowing a
    source rename to change both the winning value and its published provenance.
    """
    sources_by_entity_priority: dict[tuple[str, int], set[str]] = {}
    for vault in select_vaults(declarations):
        key = (vault["entity"], vault["source_order"])
        sources_by_entity_priority.setdefault(key, set()).add(vault["source"]["name"])

    for (entity_name, priority), source_names in sorted(sources_by_entity_priority.items()):
        if len(source_names) > 1:
            names = ", ".join(sorted(source_names))
            raise ValueError(
                f"{entity_name}: sources {names} share priority {priority} - "
                "survivorship order must be a total order; give each source feeding "
                "this entity a distinct priority"
            )


def validate_er_branch_coverage(
    declarations: list[dict[str, Any]],
    res_configs: dict[str, dict[str, Any]] | None = None,
    *,
    ctx: EstateContext | None = None,
) -> None:
    """Emit-time gate: every res_<X> model a source's bridges consume must be fed by
    an entity_resolution.<X> branch on that same source.

    A vaulted entity's bridge inner-joins res_<X> and filters `where golden_<X>_key
    is not null`. res_<X> is fanned in from the entity_resolution.<X> branches across
    all sources (see the RES loop in generate_files). If a source omits its own
    entity_resolution.<X> branch, it contributes zero records to res_<X>, resolves to
    a null golden_<X>_key, and the bridge inner-join silently drops EVERY record of
    that source downstream -- clean emit, green build, no rows. The loud-fail thesis
    forbids exactly that silent mis-emit, so this fails at emit time instead.

    The gate is keyed off the bridge's resolution MODEL (res_<X> -> <X>), not the
    vault-entity name. A rider entity (a satellite-only entity that inner-joins a
    parent's res_<X> with no entity_resolution key of its own) rides the parent's
    branch. Keying off the resolution target means those riders are satisfied by the
    source's entity_resolution.<X> branch and never false-positive. One error per
    (source, target) pair, not per entity, so several entities sharing one res model
    raise at most one error.

    A symmetric soft warning (stderr, non-fatal) fires for an entity_resolution.<X>
    branch on a source no bridge resolves against -- a branch feeding nothing.

    Branch COLUMN shape is not checked here: res_entity.sql.j2 dereferences
    branch.columns[column.name] per res column, so a branch missing an expected
    column already fails loudly (jinja2.exceptions.UndefinedError under the emitter's
    StrictUndefined Jinja environment) at render time. Duplicating it would
    break SSOT (see caveats).

    Parameterised on res_configs (rather than reading the global directly) so the
    failure path is directly testable with an injected config pair.
    """
    if res_configs is None:
        res_configs = load_domains(ctx=ctx)["res_configs"]
    res_model_to_target = {
        Path(res["path"]).stem: target for target, res in res_configs.items()
    }
    for declaration in declarations:
        source_name = declaration["source"]["name"]
        declared_branches = set(declaration.get("entity_resolution", {}))
        required: dict[str, set[str]] = {}
        for table in declaration.get("tables", {}).values():
            for vault in table.get("vault_entities", []):
                if not vault.get("enabled", True):
                    continue
                for resolution in vault.get("bridge", {}).get("resolutions", []):
                    target = res_model_to_target.get(resolution.get("model"))
                    if target is None:
                        continue
                    required.setdefault(target, set()).add(vault.get("name", vault["entity"]))
        for target in sorted(required):
            if target not in declared_branches:
                entities = ", ".join(sorted(required[target]))
                raise ValueError(
                    f"{source_name}: bridge(s) [{entities}] resolve against res_{target} "
                    f"but the source declares no entity_resolution.{target} branch; it would "
                    f"contribute no records to res_{target}, resolve to a null golden_{target}_key, "
                    f"and silently drop every row at the bridge inner-join. "
                    f"Add an entity_resolution.{target} branch to {source_name}."
                )
        for target in sorted(declared_branches - set(required)):
            print(
                f"WARN {source_name}: declares entity_resolution.{target} but no enabled bridge "
                f"resolves against res_{target}; the branch feeds no bridge.",
                file=sys.stderr,
            )


