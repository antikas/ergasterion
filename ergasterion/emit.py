def satellite_tests_yaml(
    vaults: list[dict[str, Any]], entity_configs: dict[str, dict[str, Any]]
) -> str:
    """The generated declaration pinning replay suppression on every satellite.

    One uniqueness test per satellite over its replay-suppression key, so a target
    holding a candidate row twice fails the estate build. Test arguments sit under the
    nested ``arguments:`` mapping dbt reads generic-test keyword arguments from.
    """
    lines = [
        YAML_HEADER,
        "# One uniqueness test per satellite over its replay-suppression key: business key,",
        "# hashdiff, effective column. A satellite holding the same version twice fails here.",
        "version: 2",
        "",
        "models:",
    ]
    for vault in sorted(vaults, key=lambda item: item["satellite_model"]):
        key = satellite_replay_suppression_key(vault, entity_configs)
        lines.append(f"  - name: {vault['satellite_model']}")
        lines.append("    data_tests:")
        lines.append("      - dbt_utils.unique_combination_of_columns:")
        lines.append("          arguments:")
        lines.append(f"            combination_of_columns: {py_literal(key)}")
    return "\n".join(lines) + "\n"


def _merge_key_not_null_tests(table: dict[str, Any], key_columns: list[str]) -> None:
    """Pin every derived key member not null, at error severity.

    Under delete+insert a null key member strands or duplicates rows, so the assertion
    carries error severity and halts the build before the satellites persist the batch.
    A column already carrying a plain ``not_null`` has it replaced by the severity-
    carrying form, so exactly one not-null test stands per key member.
    """
    assertion = {"not_null": {"config": {"severity": "error"}}}
    entries = table.setdefault("model_tests", [])
    by_name = {
        entry["name"]: entry
        for entry in entries
        if isinstance(entry, dict) and isinstance(entry.get("name"), str)
    }
    for column in key_columns:
        entry = by_name.get(column)
        if entry is None:
            entry = {"name": column, "data_tests": []}
            entries.append(entry)
            by_name[column] = entry
        tests = [test for test in entry.get("data_tests") or [] if test != "not_null"]
        if assertion not in tests:
            tests.append(assertion)
        entry["data_tests"] = tests


def _align_staging_grain_tests(table: dict[str, Any], key_columns: list[str]) -> None:
    """Replace an obsolete natural-key uniqueness assertion with the composite grain.

    Once staging is incremental the same natural key can legitimately occur at multiple
    effective times. Column-level ``unique`` tests on natural-key members are therefore
    removed; the schema template emits one model-level uniqueness test over the actual
    delete-and-insert key.
    """
    natural_key = set(key_columns[:-1])
    for entry in table.setdefault("model_tests", []):
        if not isinstance(entry, dict) or entry.get("name") not in natural_key:
            continue
        entry["data_tests"] = [
            test
            for test in entry.get("data_tests") or []
            if not (
                (isinstance(test, str) and test == "unique")
                or (isinstance(test, dict) and "unique" in test)
            )
        ]


def apply_staging_increments(
    declarations: list[dict[str, Any]],
    *,
    typed: Any | None = None,
) -> tuple[list[str], set[str]]:
    """Run every emit-time gate a staging increment block carries and attach the
    generated window text to the declaration tree.

    Returns the warnings emit prints and the set of window-filtered model names, which
    is what the hand-authored reference gate reads.
    """
    warnings: list[str] = []
    windowed_models: set[str] = set()
    typed_tables = getattr(typed, "tables", None) if typed is not None else None
    satellite_owners: dict[str, str] = {}
    for declaration in declarations:
        source = declaration["source"]
        source_name = source["name"]
        for table_name, table in (declaration.get("tables") or {}).items():
            block = table.get(STAGING_INCREMENT_KEY)
            if not block:
                continue
            where = f"{source.get('declaration_file', source_name)}:{table_name}"
            lookback = block["lookback_minutes"]
            effective_column = derive_effective_column(table, where)
            watermark = source_satellite_layout(
                declaration, table_name, source.get("declaration_file", source_name)
            )
            route = f"{source_name}.{table_name}"
            for entry in watermark["satellites"]:
                owner = satellite_owners.get(entry["relation"])
                if owner is not None and owner != route:
                    raise ValueError(
                        f"{source.get('declaration_file', source_name)}: satellite "
                        f"{entry['relation']!r} is fed by table routes {owner!r} and "
                        f"{route!r}, so the table-local satellite layout is not isolated "
                        f"and one table's rows could advance the other's consumption watermark"
                    )
                satellite_owners[entry["relation"]] = route

            # Emit-time column coverage: a window filters on the effective column at
            # every layer, so a declaration whose staging projection never outputs it
            # would emit clean, parse clean and fail on the executed build with a missing
            # column. It fails here instead, naming the column.
            projected = [
                column["name"]
                for column in table.get("projection", []) or []
                if isinstance(column, dict) and "name" in column
            ]
            if projected and effective_column not in projected:
                raise ValueError(
                    f"{where}: the effective column {effective_column!r} is not among the "
                    f"staging projection's output columns ({', '.join(projected)}), so every "
                    f"layer of the delta window would filter on a column the staging model "
                    f"does not carry"
                )

            # The delivery contract and the estate filter share one time fact: a
            # Bronze-backed declared table whose contract names a different event field
            # would window on a column the contract does not call the event time.
            typed_table = (
                typed_tables.get((source_name, table_name))
                if isinstance(typed_tables, dict)
                else None
            )
            contract = getattr(typed_table, "contract", None)
            if contract is not None:
                event_field = contract.delivery.timestamps.event_field
                if event_field != effective_column:
                    raise ValueError(
                        f"{where}: the Bronze Product Contract's timestamps.event_field "
                        f"{event_field!r} differs from the effective column "
                        f"{effective_column!r} a staging increment block windows on -- the "
                        f"delivery contract and the estate filter carry one time fact"
                    )

            natural_key = table.get(NATURAL_KEY_FIELD)
            if not natural_key:
                raise ValueError(
                    f"{where}: a table declaring {STAGING_INCREMENT_KEY} needs an explicit "
                    f"{NATURAL_KEY_FIELD}"
                )
            unique_key = list(natural_key)
            if effective_column not in unique_key:
                unique_key.append(effective_column)

            table["staging_increment_config"] = staging_increment_config_sql(
                unique_key, source_name, table_name, effective_column, lookback, watermark
            )
            table["staging_increment_window"] = staging_window_sql(
                source_name, table_name, effective_column, lookback, watermark
            )
            table["staging_increment_effective_column"] = effective_column
            table["staging_increment_unique_key"] = unique_key
            table["staging_increment_watermark"] = watermark
            _align_staging_grain_tests(table, unique_key)
            _merge_key_not_null_tests(table, unique_key)
            windowed_models.add(table["staging_model"])

            bridge_predicate = bridge_window_predicate_sql(
                source_name, table_name, effective_column, lookback, watermark
            )
            for vault in table.get("vault_entities", []) or []:
                if not vault.get("enabled", True):
                    continue
                bridge = vault.setdefault("bridge", {})
                clauses = bridge.setdefault("where", [])
                if bridge_predicate not in clauses:
                    clauses.append(bridge_predicate)
                vault["window_block"] = stage_window_sql(
                    EFFECTIVE_COLUMN,
                    source_name,
                    table_name,
                    effective_column,
                    lookback,
                    watermark,
                )
                windowed_models.add(vault["bridge_model"])
                windowed_models.add(vault["stage_model"])

            # A satellite on this table that carries no effective time holds this table's
            # watermark at the sentinel. Satellites on sibling tables are deliberately
            # absent from the layout and cannot affect it.
            for vault in table.get("vault_entities", []) or []:
                if not vault.get("enabled", True):
                    continue
                for column in (vault.get("bridge", {}) or {}).get("select", []) or []:
                    if not isinstance(column, dict):
                        continue
                    if column.get("name") != EFFECTIVE_COLUMN:
                        continue
                    if not _is_null_constant(column.get("expression")):
                        continue
                    notice = (
                        f"WARN staging increment on {source_name}.{table_name}: satellite "
                        f"{vault['satellite_model']} maps a null constant to "
                        f"{EFFECTIVE_COLUMN}, so this table's consumption watermark stays "
                        f"at the initial-load sentinel and its delta window stays unbounded below"
                    )
                    if notice not in warnings:
                        warnings.append(notice)
    return warnings, windowed_models


def select_vaults(declarations: list[dict[str, Any]]) -> list[dict[str, Any]]:
    vaults: list[dict[str, Any]] = []
    for declaration in declarations:
        source = declaration["source"]
        for table in declaration.get("tables", {}).values():
            for vault in table.get("vault_entities", []):
                if not vault.get("enabled", True):
                    continue
                entry = dict(vault)
                entry["source"] = source
                entry["table"] = table
                entry["source_order"] = source["priority"]
                vaults.append(entry)
    return vaults


def as_template_columns(names: list[str]) -> list[dict[str, str]]:
    return [{"name": name, "expression": name} for name in names]


def bronze_product_files(
    typed: Any, *, ctx: EstateContext | None = None
) -> list[GeneratedFile]:
    """Durable canonical Bronze Product Contract artefacts. Binding-specific
    ODCS/ODPS projections are emitted by emit_contracts / emit_odps."""
    ctx = ctx or _DEFAULT_CTX
    files: list[GeneratedFile] = []
    for table in typed.production_contracts():
        document = canonical_contract_document(table)
        path = bronze_product_dir(ctx.contracts_dir, table.logical_identity) / "bronze-product.json"
        files.append(
            GeneratedFile(
                path,
                json.dumps(document, indent=2, ensure_ascii=False) + "\n",
            )
        )
    return files


def generate_files(
    declarations: list[dict[str, Any]],
    env: Environment,
    domain: dict[str, Any],
    *,
    ctx: EstateContext | None = None,
    typed: Any | None = None,
    bound: dict | None = None,
    plan_digest: str | None = None,
) -> list[GeneratedFile]:
    # Local estate root binds this run's context; every emitted path is anchored on it.
    REPO_ROOT = (ctx or _DEFAULT_CTX).root
    entity_configs = domain["entity_configs"]
    hub_configs = domain["hub_configs"]
    link_configs = domain["link_configs"]
    bv_configs = domain["bv_configs"]
    res_configs = domain["res_configs"]
    files: list[GeneratedFile] = []
    all_tables = [
        table
        for declaration in declarations
        for table in declaration.get("tables", {}).values()
    ]
    # The window, before anything renders: every staging increment gate runs here, the
    # generated window text lands on the declaration tree, and a hand-authored model
    # reading a window-filtered relation stops generation.
    window_warnings, windowed_models = apply_staging_increments(declarations, typed=typed)
    for warning in window_warnings:
        print(warning)
    offenders = hand_authored_window_references(windowed_models, ctx=ctx or _DEFAULT_CTX)
    if offenders:
        named = "; ".join(
            f"{name} ({rel_path}) reads {referenced}"
            for name, rel_path, referenced in offenders
        )
        raise ValueError(
            f"hand-authored model(s) read a window-filtered relation: {named} -- a "
            f"window-filtered stage or bridge holds the delta window only, so a "
            f"hand-authored reader loses every row outside it; read the satellites, or "
            f"remove the staging increment block from the source table"
        )

    for table in all_tables:
        table.setdefault("visibility_join", "")
        table.setdefault("bronze_source_yaml", "")
        table.setdefault("staging_increment_config", "")
        table.setdefault("staging_increment_window", "")
    vaults = select_vaults(declarations)
    for vault in vaults:
        vault.setdefault("window_block", "")

    if typed is not None and bound:
        annotate_production_tables(
            declarations, typed, bound, plan_digest=plan_digest or bronze_plan_digest()
        )

    for table in all_tables:
        files.append(
            GeneratedFile(
                REPO_ROOT / "models" / "staging" / f"{table['staging_model']}.sql",
                render(env, "staging.sql.j2", generated_header=SQL_HEADER, table=table),
            )
        )

    for vault in vaults:
        entity = entity_configs[vault["entity"]]
        files.append(
            GeneratedFile(
                REPO_ROOT / "models" / "raw_vault" / "stage" / "bridge" / f"{vault['bridge_model']}.sql",
                render(env, "bridge.sql.j2", generated_header=SQL_HEADER, vault=vault),
            )
        )
        files.append(
            GeneratedFile(
                REPO_ROOT / "models" / "raw_vault" / "stage" / f"{vault['stage_model']}.sql",
                render(
                    env,
                    "automate_dv_stage.sql.j2",
                    generated_header=SQL_HEADER,
                    vault=vault,
                    entity=entity,
                ),
            )
        )
        files.append(
            GeneratedFile(
                REPO_ROOT / "models" / "raw_vault" / "satellites" / f"{vault['satellite_model']}.sql",
                render(
                    env,
                    "satellite.sql.j2",
                    generated_header=SQL_HEADER,
                    vault=vault,
                    entity=entity,
                    effective_column=EFFECTIVE_COLUMN,
                ),
            )
        )

    if vaults:
        files.append(
            GeneratedFile(
                REPO_ROOT.joinpath("models", *SATELLITE_TESTS_REL_PATH),
                satellite_tests_yaml(vaults, entity_configs),
            )
        )

    for hub_entity, hub in hub_configs.items():
        source_models = [vault["stage_model"] for vault in vaults if vault["entity"] == hub_entity]
        files.append(
            GeneratedFile(
                REPO_ROOT / hub["path"],
                render(
                    env,
                    "hub.sql.j2",
                    generated_header=SQL_HEADER,
                    source_models=source_models,
                    hub=hub,
                ),
            )
        )

    for link_name, link in link_configs.items():
        source_models = [
            vault["stage_model"]
            for vault in vaults
            if link_name in entity_configs[vault["entity"]]["links"]
        ]
        files.append(
            GeneratedFile(
                REPO_ROOT / link["path"],
                render(
                    env,
                    "link.sql.j2",
                    generated_header=SQL_HEADER,
                    source_models=source_models,
                    link=link,
                ),
            )
        )

    for entity_name, bv in bv_configs.items():
        entity_vaults = [vault for vault in vaults if vault["entity"] == entity_name]
        source_satellites = [
            {"name": vault["source"]["display_name"], "model": vault["satellite_model"]}
            for vault in entity_vaults
        ]
        source_priority = [vault["source"]["display_name"] for vault in entity_vaults]
        rules = {
            attr: {"strategy": strategy, "source_priority": "__SOURCE_PRIORITY__"}
            for attr, strategy in bv["rules"].items()
        }
        # The survivorship macro expects source_priority as a dbt variable, not a literal string.
        rules_literal = py_literal(rules).replace("'__SOURCE_PRIORITY__'", "source_priority")
        content = render(
            env,
            "survivorship.sql.j2",
            generated_header=SQL_HEADER,
            entity_name=entity_name,
            bv=bv,
            source_satellites=source_satellites,
            source_priority=source_priority,
            rules_set="{%- set rules = " + rules_literal + " -%}",
        )
        files.append(GeneratedFile(REPO_ROOT / bv["path"], content))

    for entity_name, res in res_configs.items():
        branches = []
        for declaration in declarations:
            branch = declaration.get("entity_resolution", {}).get(entity_name)
            if branch:
                branches.append(branch)
        res_context = dict(res)
        res_context["columns"] = as_template_columns(res["columns"])
        res_context["output_columns"] = as_template_columns(res["output_columns"])
        files.append(
            GeneratedFile(
                REPO_ROOT / res["path"],
                render(
                    env,
                    "res_entity.sql.j2",
                    generated_header=SQL_HEADER,
                    branches=branches,
                    res=res_context,
                ),
            )
        )

    seed_tables = []
    seen_seed_names: set[str] = set()
    for table in all_tables:
        if table["landing"]["kind"] != "seed":
            continue
        if table["raw_model"] not in seen_seed_names:
            seed_tables.append(table)
            seen_seed_names.add(table["raw_model"])
    source_groups_by_name: dict[str, dict[str, Any]] = {}
    source_relation_origins: dict[tuple[str, str], str] = {}
    for declaration in declarations:
        declaration_file = declaration["source"]["declaration_file"]
        for table_name, table in declaration.get("tables", {}).items():
            if table["landing"]["kind"] != "source":
                continue
            source_name = table["landing"]["source_name"]
            identifier = table["landing"]["identifier"]
            source_relation = (source_name, identifier)
            origin = f"{declaration_file}:tables.{table_name}"
            previous = source_relation_origins.get(source_relation)
            if previous is not None:
                raise ValueError(
                    f"duplicate dbt source relation source('{source_name}', '{identifier}') "
                    f"declared by {previous} and {origin}; tests and descriptions cannot "
                    "be attached without silently dropping one declaration"
                )
            source_group = source_groups_by_name.setdefault(
                source_name, {"name": source_name, "tables": []}
            )
            source_group["tables"].append(table)
            source_relation_origins[source_relation] = origin
    attach_source_physical_coords(list(source_groups_by_name.values()))
    projection_groups = (
        production_projection_groups(typed, bound) if typed is not None and bound else []
    )
    files.append(
        GeneratedFile(
            REPO_ROOT / "models" / "staging" / "_sources.yml",
            render(
                env,
                "sources.yml.j2",
                generated_header=YAML_HEADER,
                seed_tables=seed_tables,
                source_groups=list(source_groups_by_name.values()),
                projection_source_groups=projection_groups,
                staging_tables=all_tables,
            ),
        )
    )
    if typed is not None:
        files.extend(bronze_product_files(typed, ctx=ctx or _DEFAULT_CTX))
    return files


def write_files(
    files: list[GeneratedFile], check: bool = False, *, root: Path | None = None
) -> list[Path]:
    changed: list[Path] = []
    for file in files:
        if root is not None and not file.path.resolve().is_relative_to(Path(root).resolve()):
            raise ValueError(
                f"refusing to write {file.path}: resolved outside the estate root {root}"
            )
        existing = file.path.read_text(encoding="utf-8") if file.path.exists() else None
        if existing == file.content:
            continue
        changed.append(file.path)
        if check:
            before = existing.splitlines() if existing is not None else []
            after = file.content.splitlines()
            diff = "\n".join(
                difflib.unified_diff(before, after, fromfile=str(file.path), tofile=str(file.path))
            )
            print(diff)
            continue
        file.path.parent.mkdir(parents=True, exist_ok=True)
        # JSON artefacts and the evolution ledgers are written as bytes, so their
        # newlines stay LF on every platform and a Windows checkout under
        # core.autocrlf=true round-trips them byte-identically.
        if file.path.suffix == ".json" or file.path.name.endswith(EVOLUTION_LEDGER_SUFFIX):
            file.path.write_bytes(file.content.encode("utf-8"))
        else:
            file.path.write_text(file.content, encoding="utf-8")
    return changed


def prune_orphaned_files(
    generated_paths: set[Path], check: bool = False, *, ctx: EstateContext | None = None
) -> list[Path]:
    """Delete generated files that are no longer in the current generated set.

    Scans the models tree for files marked with GENERATED_MARKER and removes
    any that are not in the current generated_paths set. This prevents orphaned
    files from accumulating when declarations are removed or renamed.

    Args:
        generated_paths: Set of all paths that should be generated from current
            declarations (typically from GeneratedFile objects)
        check: If True, report would-delete without deleting

    Returns:
        List of paths that were (or would be) deleted, in relative form
    """
    deleted: list[Path] = []
    ctx = ctx or _DEFAULT_CTX
    REPO_ROOT = ctx.root
    MODELS_DIR = ctx.models_dir

    # Scan for emitted SQL and YAML files marked with GENERATED_MARKER
    # Scope to models/ only to avoid dbt build artifacts in target/
    for ext in ("*.sql", "*.yml"):
        for path in MODELS_DIR.rglob(ext):
            if not _is_generated(path):
                continue
            if path in generated_paths:
                continue
            # This file was generated but is no longer in the set
            deleted.append(path.relative_to(REPO_ROOT))
            if not check:
                path.unlink()

    bronze_root = ctx.contracts_dir / "bronze"
    if bronze_root.exists():
        for path in bronze_root.rglob("bronze-product.json"):
            if path in generated_paths:
                continue
            deleted.append(path.relative_to(REPO_ROOT))
            if not check:
                path.unlink()

    # Sort for deterministic output across platforms
    return sorted(deleted)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Print diffs without writing files.")
    parser.add_argument(
        "--estate-root",
        type=Path,
        default=None,
        help=(
            "Root of the data-product ESTATE to emit against (declarations/, domains/, "
            "models/, ...). Highest-precedence override of the estate-root resolution chain "
            "(--estate-root > DPF_ESTATE_ROOT env > walk-up from cwd to the nearest "
            "dbt_project.yml+domains/ ancestor > the package's own source tree). Engine "
            "data (templates, schemas) is package-relative and NOT affected by this."
        ),
    )
    parser.add_argument(
        "--openim-root",
        type=Path,
        default=None,
        help=(
            "OpenIM repo root used for the investment domain's OPTIONAL, per-domain "
            "canonical-mapping validation. Skip-safe: absent (the default) or missing, the "
            "check WARN-skips (a domain with no canonical_mappings needs no model repo)."
        ),
    )
    parser.add_argument(
        "--domains-dir",
        type=Path,
        default=None,
        help=(
            "Directory of per-domain model-config YAML (domains/*.yml). Defaults to the "
            "resolved estate's domains/. All files are merged; a second domain is onboarded "
            "by adding a file here plus declarations, with no engine change."
        ),
    )
    parser.add_argument(
        "--strict-openim",
        action="store_true",
        help=(
            "Fail (non-zero exit) instead of WARN-skipping when the optional OpenIM "
            "canonical-mapping validation cannot run -- no --openim-root given, or the "
            "given root does not resolve to a checkout. Default: unchanged, WARN-skip "
            "only (see --openim-root above); this flag changes only the exit code, never "
            "what gets generated."
        ),
    )
    parser.add_argument(
        "--lint-target",
        default=os.environ.get("DPF_LINT_TARGET"),
        help=(
            "Additional registered adapter for the post-emit dialect gate (also read "
            "from DPF_LINT_TARGET). All declared deployment adapters are always "
            "linted; a requested registered adapter is added when it is not declared."
        ),
    )
    parser.add_argument(
        "--binding",
        type=Path,
        default=None,
        help=(
            "RuntimeBinding YAML file or directory. Required when any production "
            "Bronze source is declared; --environment must equal each binding's "
            "environment."
        ),
    )
    parser.add_argument(
        "--environment",
        default=None,
        help="Mandatory matching assertion against RuntimeBinding.environment.",
    )
    args = parser.parse_args()

    ctx = EstateContext.resolve(
        estate_root=args.estate_root,
        openim_root=args.openim_root,
        domains_dir=args.domains_dir,
    )

    domain = load_domains(ctx=ctx)
    validate_bv_rules_subset_of_payload(domain["bv_configs"], domain["entity_configs"])
    validate_domain_paths(domain)
    validate_res_configs(domain["res_configs"], ctx=ctx)
    declarations = load_declarations(domain, ctx=ctx)
    validate_unique_source_priorities(declarations)
    validate_er_branch_coverage(declarations, domain["res_configs"], ctx=ctx)
    try:
        check_casefold_identities(declarations)
        typed = load_typed_declarations(ctx)
        reject_draft_generation(typed)
    except ValueError as error:
        print(f"FAIL: {error}")
        return 1
    bound = {}
    plan_digest = None
    if typed.production_contracts():
        if args.binding is None or args.environment is None:
            print(
                "FAIL: production Bronze generation needs --binding PATH and "
                "--environment NAME"
            )
            return 2
        try:
            bindings = load_runtime_bindings(args.binding, args.environment)
            plan_digest = bronze_plan_digest()
            bound = bind_production_sources(typed, bindings)
        except ValueError as error:
            print(f"FAIL: {error}")
            return 2
    warning_count = validate_canonical_mappings(declarations, ctx.openim_root)
    # Estate evolution runs before generation: it freezes each entity's hashdiff basis
    # at the value its stored hashdiffs were computed over, so an extension reaches the
    # payload without moving a single stored fingerprint, and it stops emit on every
    # non-additive change with the estate migration requirement.
    try:
        ledger_files, evolution_notices = grade_estate_evolution(
            domain, declarations, ctx=ctx, typed=typed
        )
    except ValueError as error:
        print(f"FAIL: {error}")
        return 1
    for notice in evolution_notices:
        print(notice)
    env = template_env()
    files = generate_files(
        declarations, env, domain, ctx=ctx, typed=typed, bound=bound, plan_digest=plan_digest
    )
    files.extend(ledger_files)
    changed = write_files(files, check=args.check, root=ctx.root)
    action = "would change" if args.check else "generated"
    summary = f"{action} {len(changed)} of {len(files)} files"
    if warning_count:
        summary += f" ({warning_count} warning{'s' if warning_count != 1 else ''})"
    print(summary)
    for path in changed:
        print(path.relative_to(ctx.root).as_posix())

    # Prune orphaned generated files (those no longer declared)
    generated_paths = {file.path for file in files}
    deleted = prune_orphaned_files(generated_paths, check=args.check, ctx=ctx)
    if deleted:
        prune_action = "would delete" if args.check else "deleted"
        print(f"{prune_action} {len(deleted)} orphaned generated file(s)")
        for path in deleted:
            print(path.as_posix())
    # Structural, machine-readable orphan signal: a stable marker line, printed on
    # EVERY run (including ORPHANS=0), independent of the prose above. A caller that
    # needs to know whether orphans exist parses this line instead of grepping the
    # human-facing message, which can be reworded without the signal moving.
    print(f"ORPHANS={len(deleted)}")

    # Factory gate: every deployment adapter declared under declarations/targets/
    # gets its own dialect pass in this invocation. Declaration loading and the
    # deployment-kind filter are shared with structure_gate rather than re-derived.
    try:
        target_declarations, _ = load_structure_declarations(ctx)
    except ValueError as error:
        print(f"structure-gate FAIL: {error}")
        return 1

    try:
        lint_targets = [
            declaration.adapter
            for declaration in target_declarations
            if declaration.kind == "deployment"
        ]
        if args.lint_target and args.lint_target not in DENY_LISTS:
            raise ValueError(
                f"--lint-target/DPF_LINT_TARGET names unknown adapter {args.lint_target!r}; "
                "it must be registered in ergasterion.dialect_lint.DENY_LISTS"
            )
        if args.lint_target:
            print(
                f"dialect-lint compatibility target {args.lint_target!r} acknowledged; "
                "checking every declared deployment adapter"
            )
            if args.lint_target not in lint_targets:
                lint_targets.append(args.lint_target)
        for lint_target in lint_targets:
            offenses = lint_models(lint_target, ctx=ctx)
            if offenses:
                print(
                    f"dialect-lint FAIL [{lint_target}]: {len(offenses)} "
                    "incompatible construct(s) in model/test SQL:"
                )
                for off in offenses:
                    rel = off.path.relative_to(ctx.root).as_posix()
                    print(f"  {rel}:{off.line_no}  [{off.token}]  {off.message}")
                return 1
            print(f"dialect-lint OK [{lint_target}]: model/test SQL clean")
    except ValueError as error:
        print(f"dialect-lint FAIL: {error}")
        return 1

    # Factory gate: the estate stays within every declared target's structural
    # budgets (declarations/targets/*.yml) -- materialisation boundaries, view
    # chain depth, statement size, identifier length, metadata payload. The
    # checks and the declaration format live in ergasterion/structure_gate.py.
    try:
        structure_offenses = check_structure(ctx)
    except ValueError as error:
        print(f"structure-gate FAIL: {error}")
        return 1
    if structure_offenses:
        print(f"structure-gate FAIL: {len(structure_offenses)} budget offense(s):")
        for offense in structure_offenses:
            print(
                f"  [{offense.adapter}] {offense.budget}: {offense.artefact} -- "
                f"{offense.message}"
            )
        return 1
    print("structure-gate OK: estate within every declared target budget")

    if args.strict_openim and warning_count:
        print(
            f"FAIL --strict-openim: OpenIM canonical mapping validation was skipped "
            f"({warning_count} warning{'s' if warning_count != 1 else ''}); rerun with "
            f"--openim-root pointed at a real checkout, or drop --strict-openim.",
            file=sys.stderr,
        )
        return 1

    # --check fails on either an unwritten diff OR an orphan that would be pruned:
    # both mean the on-disk tree does not match current declarations. Orphans used
    # to be reported (see the prose above and ORPHANS=<n>) without moving this exit
    # code, so a --check run with only orphans and no other diff exited 0 -- a
    # fail-open silently papered over by validators grepping the prose message.
    return 1 if args.check and (changed or deleted) else 0


if __name__ == "__main__":
    raise SystemExit(main())
