"""The generated-file marker: one text, one owner.

Every artefact the engine writes into an estate carries this marker on its
first line. It is what tells a reader, a gate and a person that the file is
an output of a declaration rather than something a person wrote:

  * the SQL translator writes ``SQL_HEADER`` on every ``.sql`` artefact and
    ``YAML_HEADER`` on every ``.yml`` artefact it renders;
  * ``ergasterion.dialect_lint`` reads ``GENERATED_MARKER`` back to decide
    which files under an estate's model tree are generated, and therefore
    which ones its deny lists apply to;
  * ``ergasterion.structure_gate`` reads it through the same function for
    the generated-or-hand-authored classification.

Holding the three strings here rather than in the writer or the reader is
the point: a marker defined twice can drift, and a drifted marker silently
reclassifies a whole tree as hand-authored. Every reader and every writer
imports these names from this module.

The comment prefixes are the two the engine emits. A file format that needs
a third supplies it here, never in the module that writes that format.
"""
from __future__ import annotations

# The marker itself. Plain ASCII, no path and no module name: the route that
# writes a file is an implementation detail that has already changed once,
# and a marker naming it goes stale in every generated file at the same time.
GENERATED_MARKER = "Generated by Ergasterion from a product declaration. Do not edit by hand."

# The two comment forms the engine writes.
SQL_HEADER = f"-- {GENERATED_MARKER}"
YAML_HEADER = f"# {GENERATED_MARKER}"

__all__ = ["GENERATED_MARKER", "SQL_HEADER", "YAML_HEADER"]
